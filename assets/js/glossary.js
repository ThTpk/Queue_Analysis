  /* ---------------------------------------------------------- auto-link */
  const SKIP = 'script,style,pre,code,a,button,h1,h2,h3,h4,.katex,.gloss,.calc,input,select,svg,canvas';

  function autolink() {
    const hosts = document.querySelectorAll(
      'main p, main li, main td, main th, main figcaption, main .lede, main .d, main .sub');
    const done = new Set();
    /* เรียงคำยาวก่อน เพื่อให้ Erlang-C ถูกจับก่อน erlang */
    const terms = [];
    GLOSS.forEach(g => g.m.forEach(m => terms.push({ m, g })));
    terms.sort((a, b) => b.m.length - a.m.length);

    for (const host of hosts) {
      if (host.closest('.gloss-skip')) continue;
      const walker = document.createTreeWalker(host, NodeFilter.SHOW_TEXT, {
        acceptNode(n) {
          if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
          return n.parentElement && n.parentElement.closest(SKIP)
            ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
        },
      });
      const nodes = [];
      let n;
      while ((n = walker.nextNode())) nodes.push(n);
      for (const node of nodes) {
        for (const { m, g } of terms) {
          if (done.has(g.id)) continue;
          const i = node.nodeValue.indexOf(m);
          if (i < 0) continue;
          const after = node.splitText(i);
          after.splitText(m.length);
          const btn = document.createElement('button');
          btn.className = 'gloss';
          btn.type = 'button';
          btn.textContent = m;
          btn.dataset.g = g.id;
          btn.setAttribute('aria-label', m + ' — ' + g.s);
          after.parentNode.replaceChild(btn, after);
          done.add(g.id);
          break;                      /* หนึ่ง text node จับได้ครั้งเดียว ป้องกันซ้อน */
        }
      }
    }
    return done.size;
  }

  /* ---------------------------------------------------------- popover */
  let pop = null;
  function closePop() { if (pop) { pop.remove(); pop = null; } }
  function openPop(btn) {
    closePop();
    const g = byId[btn.dataset.g];
    if (!g) return;
    pop = document.createElement('div');
    pop.className = 'gloss-pop';
    pop.innerHTML = '<div class="gt">' + g.t + '</div><p>' + g.s + '</p>' +
      '<p class="gl">' + g.l + '</p>' +
      '<a href="' + (document.body.dataset.base || '') + 'glossary.html#' + g.id + '">ดูในอภิธานศัพท์ →</a>';
    document.body.appendChild(pop);
    /* วางด้วยพิกัดหน้าจอ (position: fixed) จึงไม่ต้องสนว่า ancestor ตัวไหนเป็น containing block */
    const r = btn.getBoundingClientRect();
    const w = Math.min(340, window.innerWidth - 24);
    pop.style.width = w + 'px';
    let left = r.left + r.width / 2 - w / 2;
    left = Math.max(12, Math.min(left, window.innerWidth - w - 12));
    pop.style.left = left + 'px';
    const h = pop.offsetHeight;
    pop.style.top = (r.bottom + h + 16 > window.innerHeight && r.top - h - 8 > 8
      ? r.top - h - 8 : r.bottom + 8) + 'px';
  }

  function init() {
    if (!document.querySelector('main')) return;
    autolink();
    document.addEventListener('click', e => {
      const b = e.target.closest && e.target.closest('button.gloss');
      if (b) { e.preventDefault(); if (pop && pop.dataset.for === b.dataset.g) closePop();
        else { openPop(b); if (pop) pop.dataset.for = b.dataset.g; } return; }
      if (pop && !e.target.closest('.gloss-pop')) closePop();
    });
    document.addEventListener('keydown', e => { if (e.key === 'Escape') closePop(); });
    window.addEventListener('resize', closePop);
    window.addEventListener('scroll', closePop, { passive: true });
  }

  /* รอให้ KaTeX วาดสูตรเสร็จก่อน จะได้ไม่ไปแตะข้อความในสูตร */
  if (document.readyState === 'complete') setTimeout(init, 60);
  else window.addEventListener('load', () => setTimeout(init, 60));

  global.GLOSS = GLOSS;
  global.GLOSS_BY_ID = byId;
